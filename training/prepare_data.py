"""STEP 1 - Read the raw files and describe them.
Reads : Annotatation file.csv, metadata.xlsx, 'Annotated Images/'
Writes: work/labels.csv  (one clean row per image)  and  work/data_report.md"""
import re, collections
import pandas as pd
from training.settings import *
from training.common import image_key, patient_id

WORK.mkdir(parents=True, exist_ok=True)


def parse_attrs(s):
    """The CSV stores labels as JSON-ish text, and some rows are malformed,
    so pull out every "key":"value" pair with a regex instead of json.loads."""
    if not isinstance(s, str):
        return {}
    return dict(re.findall(r'"([^"]+)"\s*:\s*"([^"]*)"', s.replace('""', '"')))


raw = pd.read_csv(CSV_FILE).dropna(subset=["filename"])
disk = sorted(p.name for p in IMG_DIR.glob("*.jpg"))
disk_by_key = {image_key(f): f for f in disk}

rows = []
for fname, g in raw.groupby("filename", sort=False):
    attrs = parse_attrs(g.iloc[0]["file_attributes"])
    reg = [parse_attrs(x) for x in g["region_attributes"].dropna()]
    disk_name = disk_by_key.get(image_key(fname))
    rows.append(dict(
        csv_filename=fname, disk_filename=disk_name,
        combined_id=Path(disk_name).stem if disk_name else None,           # rebuilt, unique key = file name without .jpg
        csv_combined_id=g.iloc[0].get("Combined ID"),                      # value stored in the CSV (unreliable, see report)
        patient=patient_id(disk_name) if disk_name else None,
        eye={"LE": "Left", "RE": "Right"}.get(disk_name.split("_")[1], "?") if disk_name else None,
        diagnosis=attrs.get("Diagnosis Category"), dr_grade=attrs.get("DR Category"),
        macular_edema=attrs.get("Macular Edema"), image_quality=attrs.get("Image Quality"),
        quality_grade=attrs.get("Grading of Image Quality"),
        n_lesion_regions=sum(1 for r in reg if r.get("Retinal Pathological Appearance")),
        lesion_types="; ".join(sorted({r.get("Retinal Pathological Appearance", "") for r in reg} - {""})),
    ))
lab = pd.DataFrame(rows)
usable = lab[lab.disk_filename.notna() & lab.diagnosis.isin(CLASSES)].copy()
usable.to_csv(WORK / "labels.csv", index=False)

meta = pd.read_excel(META_FILE)
L = []
L.append("# Data report (generated by step 1)\n")
L.append(f"- Images on disk: **{len(disk)}**")
L.append(f"- Unique images listed in annotation CSV: **{len(lab)}** ({len(raw)} rows - one row per drawn lesion region)")
L.append(f"- Images with a usable label that exist on disk: **{len(usable)}**")
L.append(f"- Images on disk with no annotation (skipped): {len(set(disk) - set(usable.disk_filename))}")
L.append(f"- CSV entries with a missing/unreadable label (skipped): {int((~lab.diagnosis.isin(CLASSES)).sum())}")
L.append(f"- Distinct patients: **{usable.patient.nunique()}**")
ok = (usable.combined_id == usable.csv_combined_id)
L.append(f"- **Combined ID check:** the CSV 'Combined ID' column has only {usable.csv_combined_id.nunique()} distinct values for {len(usable)} images and equals the "
         f"image file name for just {int(ok.sum())} of them; the other {int((~ok).sum())} are stale copies of another row's ID (wrong patient number). "
         "Reports therefore use `combined_id` = image file name without .jpg (unique), and keep the CSV value in `csv_combined_id`.\n")
L.append("## Target classes (Diagnosis Category)\n")
L.append(usable.diagnosis.value_counts().to_markdown() + "\n")
L.append("## DR severity inside the DR class\n")
L.append(usable[usable.diagnosis == "DR"].dr_grade.value_counts().to_markdown() + "\n")
L.append("## Image quality grade vs diagnosis\n")
L.append(pd.crosstab(usable.quality_grade, usable.diagnosis).to_markdown() + "\n")
L.append("## Most common annotated lesion types\n")
c = collections.Counter(t for s in usable.lesion_types for t in s.split("; ") if t)
L.append(pd.Series(c).sort_values(ascending=False).to_markdown() + "\n")
L.append(f"## metadata.xlsx\n\n{meta.shape[0]} patient records x {meta.shape[1]} columns (demographics, vitals, eye exam). "
         "It is **not** used for image training (see PROCESS.md for why).\n")
(WORK / "data_report.md").write_text("\n".join(L), encoding="utf-8")
print("\n".join(L))
