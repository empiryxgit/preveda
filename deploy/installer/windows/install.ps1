<#
 PreVeda Madhu-DR - one-click installer
 1. checks for Docker (installs Docker Desktop via winget if missing)
 2. starts Docker and waits until it is ready
 3. shares local drives read-only (no questions), builds the single container image and runs it
 4. opens the web app in your browser
 Log: install.log (next to this file)
#>
$ErrorActionPreference = 'Stop'
$Root    = $PSScriptRoot
$App     = Join-Path $Root 'app'
$Compose = Join-Path $App 'deploy\docker\docker-compose.yml'
try { Start-Transcript -Path (Join-Path $Root 'install.log') -Append | Out-Null } catch {}

function Step($m) { Write-Host "`n==> $m" -ForegroundColor Cyan }
function Good($m) { Write-Host "    OK  $m" -ForegroundColor Green }
function Warn($m) { Write-Host "    !!  $m" -ForegroundColor Yellow }
function Stop-Here($m) { Write-Host "`n$m" -ForegroundColor Red; try { Stop-Transcript | Out-Null } catch {}; exit 1 }

function Test-Engine {
    $old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    try { & docker info 2>$null | Out-Null; return ($LASTEXITCODE -eq 0) } catch { return $false }
    finally { $ErrorActionPreference = $old }
}
function Test-PortFree($p) { -not (Get-NetTCPConnection -LocalPort $p -State Listen -ErrorAction SilentlyContinue) }
function Find-Port($start) { $p = $start; while (-not (Test-PortFree $p) -and $p -lt ($start + 50)) { $p++ }; $p }
function Add-DockerToPath {
    $bin = Join-Path $env:ProgramFiles 'Docker\Docker\resources\bin'
    if ((Test-Path $bin) -and ($env:Path -notlike "*$bin*")) { $env:Path = "$bin;$env:Path" }
}

Write-Host "PreVeda Madhu-DR installer" -ForegroundColor White
if (-not (Test-Path $Compose)) { Stop-Here "Cannot find the application files ($Compose). Keep this installer next to the 'app' folder." }

# ---- 1. Docker present? ------------------------------------------------------
Step "Checking for Docker"
Add-DockerToPath
if (Get-Command docker -ErrorAction SilentlyContinue) {
    Good "Docker is installed"
} else {
    Warn "Docker is not installed."
    if (Get-Command winget -ErrorAction SilentlyContinue) {
        Step "Installing Docker Desktop (a Windows permission prompt may appear)"
        & winget install -e --id Docker.DockerDesktop --accept-package-agreements --accept-source-agreements
        if ($LASTEXITCODE -ne 0) { Stop-Here "Docker Desktop installation did not finish. Install it from https://www.docker.com/products/docker-desktop/ and run this installer again." }
        Add-DockerToPath
        Good "Docker Desktop installed"
    } else {
        Start-Process "https://www.docker.com/products/docker-desktop/"
        Stop-Here "winget is not available. Install Docker Desktop from the page that just opened, then run this installer again."
    }
}

# ---- 2. Engine running? ------------------------------------------------------
Step "Making sure Docker is running"
if (-not (Test-Engine)) {
    $exe = Join-Path $env:ProgramFiles 'Docker\Docker\Docker Desktop.exe'
    if (Test-Path $exe) { Start-Process $exe | Out-Null } else { Warn "Docker Desktop.exe not found; waiting for the engine anyway." }
    Write-Host "    Waiting for Docker to start (up to 5 minutes)..."
    $deadline = (Get-Date).AddMinutes(5)
    while (-not (Test-Engine) -and (Get-Date) -lt $deadline) { Start-Sleep -Seconds 5; Write-Host -NoNewline "." }
    Write-Host ""
}
if (-not (Test-Engine)) {
    Stop-Here @"
Docker is installed but not ready yet. This is normal on a first install.
  1. If Windows asks you to restart, restart now.
  2. Open Docker Desktop once and accept its terms.
  3. Wait until it says 'Engine running', then double-click this installer again.
"@
}
Good "Docker engine is running"

# ---- 2b. Share local drives (read-only) so any folder can be chosen later in the app -------------------------------------
Step "Sharing local drives read-only with Madhu-DR"
$EnvFile    = Join-Path (Split-Path $Compose) '.env'
$DrivesFile = Join-Path (Split-Path $Compose) 'docker-compose.drives.yml'
$fixed = @(Get-CimInstance Win32_LogicalDisk -Filter "DriveType=3" | ForEach-Object { $_.DeviceID.Substring(0,1).ToUpper() })
if ($fixed.Count -eq 0) { $fixed = @('C') }
Write-Host "    No questions asked: all local drives are shared read-only. You pick the image folder later in the web app (Settings)."
$drives = $fixed
$drives = @($drives | Where-Object { Test-Path "$($_):\" })
if ($drives.Count -eq 0) { Stop-Here "None of those drives exist on this computer." }
$lines = @('# Generated by Install-PreVeda.bat: drives shared read-only with the container', 'services:', '  madhu-dr:', '    volumes:')
foreach ($d in $drives) { $lines += @('      - type: bind', "        source: $($d):/", "        target: /host/$($d.ToLower())", '        read_only: true') }
Set-Content -Path $DrivesFile -Value $lines -Encoding ASCII
$pathMap = ($drives | ForEach-Object { "$($_):=/host/$($_.ToLower())" }) -join ','
$ComposeArgs = @('-f', $Compose, '-f', $DrivesFile)
$ImagesDir = Join-Path $Root 'images'
if (-not (Test-Path $ImagesDir)) { New-Item -ItemType Directory -Path $ImagesDir -Force | Out-Null }
$imgDir = (Resolve-Path -LiteralPath $ImagesDir).Path -replace '\\','/'
Good "Drives shared (read-only): $($drives -join ', ')"

# ---- 2c. Two ports: REST API and web app ---------------------------------------
Step "Choosing ports for the API and the web app"
$old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
& docker compose @ComposeArgs down 2>$null | Out-Null      # frees our own ports on a re-run; saved results are kept
$ErrorActionPreference = $old
$ApiPort = Find-Port 8080
$WebPort = Find-Port ([Math]::Max(8081, $ApiPort + 1))
if ($ApiPort -ne 8080 -or $WebPort -ne 8081) { Warn "Default ports were busy; using $ApiPort and $WebPort." }
Set-Content -Path $EnvFile -Value @("PREVEDA_HOST_IMAGES_DIR=$imgDir", "PREVEDA_PATH_MAP=$pathMap", "PREVEDA_API_PORT=$ApiPort", "PREVEDA_WEB_PORT=$WebPort") -Encoding ASCII
$ApiUrl = "http://localhost:$ApiPort"; $WebUrl = "http://localhost:$WebPort"
Good "API  -> $ApiUrl"
Good "Web  -> $WebUrl"

# ---- 3. Build and run --------------------------------------------------------
Step "Building and starting PreVeda Madhu-DR (first run downloads packages; this can take several minutes)"
& docker compose @ComposeArgs up -d --build
if ($LASTEXITCODE -ne 0) { Stop-Here "The build or start failed. See install.log for details. If a port is busy, close the program using it and run this installer again." }

# ---- 4. Wait until ready -----------------------------------------------------
Step "Waiting for the service to become ready"
$ready = $false
for ($i = 0; $i -lt 60; $i++) {
    try { $r = Invoke-WebRequest -UseBasicParsing -Uri "$ApiUrl/ready" -TimeoutSec 3; if ($r.StatusCode -eq 200) { $ready = $true; break } } catch {}
    Start-Sleep -Seconds 2
}
if (-not $ready) { Stop-Here "The container started but did not report ready. Run:  docker logs preveda-madhu-dr  and share the output." }

Good "Madhu-DR is running"
Write-Host "`n  Web app : $WebUrl   (sign in: doctor / doctor123  or  admin / admin123)" -ForegroundColor Green
Write-Host "  REST API: $ApiUrl/docs" -ForegroundColor Green
Write-Host "`nTo stop it, run Stop-PreVeda.bat." -ForegroundColor Green
Start-Process $WebUrl
try { Stop-Transcript | Out-Null } catch {}
